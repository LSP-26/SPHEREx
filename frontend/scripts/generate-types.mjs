// Generates src/generated/*.ts from the JSON schema the backend exports
// (python -m contracts.export_schema). Run: npm run types. CI checks that nothing changes.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const here = path.dirname(fileURLToPath(import.meta.url));
const schemaDir = path.resolve(here, "../../contracts/schema");
const outDir = path.resolve(here, "../src/generated");
const names = ["FlipbookRequest", "FrameRef", "FrameLabel", "Event", "JobHandle", "PollResponse"];

fs.mkdirSync(outDir, { recursive: true });
for (const name of names) {
  const schema = JSON.parse(fs.readFileSync(path.join(schemaDir, `${name}.json`), "utf8"));
  const ts = await compile(schema, name, {
    bannerComment: "/* Generated by `npm run types` from contracts/schema. Do not edit. */",
    additionalProperties: false,
    unknownAny: false,
  });
  fs.writeFileSync(path.join(outDir, `${name}.ts`), ts);
}
console.log(`wrote ${names.length} files to src/generated`);
